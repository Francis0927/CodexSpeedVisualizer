(async () => {
  const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const invoke = (name, args) => window.__TAURI_INTERNALS__.invoke(name, args);
  const checks = [];
  try {
    for (let n = 0; n < 100 && !document.querySelector('.speed-card'); n++) await sleep(100);
    assert(window.speedPet && document.querySelector('.speed-card'), 'React dashboard loaded');
    const initialUsage = (await window.speedPet.getInitial()).usage;
    assert(initialUsage.total === 140 && initialUsage.historyTotal === 140, 'Rust collector delivered synthetic usage');
    checks.push('Rust usage to React');
    await window.speedPet.updateSettings({ size: 'small', autoHideChrome: true, reducedMotion: true });
    await sleep(250);
    assert(document.querySelector('.view-small'), 'small view');
    assert(document.querySelector('.reduce-motion'), 'reduced motion');
    checks.push('React bridge and small view');
    document.querySelector('[aria-label="设置"]').click();
    await sleep(250);
    assert(document.querySelector('.view-medium'), 'small settings grows to medium');
    assert((await window.speedPet.getInitial()).settings.size === 'small', 'selected small size retained');
    checks.push('settings temporary medium size');
    document.querySelector('[aria-label="设置"]').click();
    await sleep(250);
    assert(document.querySelector('.view-small'), 'close restores small view');
    document.querySelector('.shell').dispatchEvent(new MouseEvent('mouseout', { bubbles: true, relatedTarget: document.body }));
    await sleep(4300);
    assert(document.querySelector('.is-collapsed'), 'idle folding');
    const before = { width: innerWidth, height: innerHeight };
    await invoke('test_update_status', { status: { state: 'available', version: '99.0.0', notes: '更新说明'.repeat(100), message: null } });
    await sleep(250);
    assert(document.querySelector('.is-collapsed'), 'background update preserves folding');
    assert(innerWidth === before.width && innerHeight === before.height, 'background update preserves bounds');
    assert(document.querySelector('.has-update'), 'update badge');
    checks.push('background update preserves bounds, panel and folding');
    document.querySelector('.shell').dispatchEvent(new MouseEvent('mouseover', { bubbles: true, relatedTarget: document.body }));
    await sleep(250);
    assert(!document.querySelector('.is-collapsed'), 'hover unfolds');
    document.querySelector('.speed-card').click();
    await sleep(250);
    assert(document.querySelector('.view-medium'), 'details temporary medium size');
    checks.push('hover and details');
    await window.speedPet.updateSettings({ size: 'large', autoHideChrome: false });
    await sleep(250);
    assert(document.querySelector('.view-large'), 'large view');
    assert(innerHeight >= document.querySelector('.viewport').getBoundingClientRect().height - 2, 'content height not clipped');
    checks.push('large view and content height');
    const initial = await window.speedPet.getInitial();
    assert(initial.settings.historyResetAt === 12345 || initial.settings.historyResetAt === undefined, 'legacy reset preserved');
    await invoke('test_report', { result: { passed: true, checks, version: initial.appInfo.version, usage: initial.usage, settings: initial.settings } });
  } catch (error) { await invoke('test_report', { result: { passed: false, error: String(error), checks } }); }
})();
